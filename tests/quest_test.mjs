import { chromium } from '/opt/npm-tools/node_modules/playwright/index.mjs';
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--no-sandbox'] });
const errs = []; let fails = 0;
const ok = (c, m, x = '') => { console.log((c ? 'PASS ' : 'FAIL ') + m, x); if (!c) fails++; };
const ctx = await browser.newContext({ viewport: { width: 1280, height: 720 } });
await ctx.route((u) => u.hostname !== 'localhost', (r) => r.abort());
const p = await ctx.newPage(); p.on('pageerror', (e) => errs.push(e.message));
await p.goto('http://localhost:8787/', { waitUntil: 'domcontentloaded' }); await p.waitForTimeout(3000);
await p.evaluate(() => { window.__ember.lockQuality(); window.__ember.idleAfter = 3600000; });
await p.click('#pick-animal button:nth-child(1)'); await p.click('#enter'); await p.waitForTimeout(4000);
const q = () => p.evaluate(() => JSON.parse(localStorage.getItem('ember.quests') || '{}'));
const acts = () => p.evaluate(() => [...document.querySelectorAll('button')].filter((b) => b.offsetParent).map((b) => b.textContent.trim()));
const press = async (re) => { const list = await acts(); const t = list.find((x) => re.test(x)); if (!t) { console.log('  no button', re, list.slice(-8).join(' | ')); return false; } await p.locator('button', { hasText: t.replace(/^[A-Z](?=[A-Z])/, '') }).first().click(); return true; };
ok(Object.keys(await q()).length === 0, 'a newcomer has no quests done');
ok(await p.evaluate(() => getComputedStyle(document.getElementById('tasks')).display === 'none' || document.getElementById('tasks').dataset.fresh === 'true'), 'the quests panel waits until the fire is reached');
await p.evaluate(() => window.__ember.teleport(0, 4, 3.1)); await p.waitForTimeout(1500);
ok(!!(await q()).cold, 'reaching the fire is the first quest');
console.log('  flash:', await p.evaluate(() => document.getElementById('flash-title').textContent + ' / ' + document.getElementById('flash-sub').textContent));
console.log('  panel:', (await p.evaluate(() => document.getElementById('tasks').innerText)).replace(/\n+/g, ' | '));
console.log('  goal:', await p.evaluate(() => document.getElementById('goal-text').textContent));
await p.screenshot({ path: '/home/claude/ember-isle/shots/q1.png' });
await p.evaluate(() => window.__ember.teleport(3.1, 6.2, 3.1)); await p.waitForTimeout(1200);
await press(/stick|wood/i); await p.waitForTimeout(1200);
await p.evaluate(() => window.__ember.teleport(0, 2.6, 3.1)); await p.waitForTimeout(1200);
await press(/fire/i); await p.waitForTimeout(3500);
await p.waitForTimeout(2500); ok(!!(await q()).burn, 'feeding the fire is the second');
await p.screenshot({ path: '/home/claude/ember-isle/shots/q2.png' });
console.log('  goal:', await p.evaluate(() => document.getElementById('goal-text').textContent));
await p.waitForTimeout(3000);
console.log('  log:', (await p.evaluate(() => [...document.querySelectorAll('#log > *')].slice(-5).map((e) => e.textContent).join(' || '))));
await p.evaluate(() => window.__ember.teleport(0.6, 3.4, 3.1)); await p.waitForTimeout(1200);
await press(/Greet the Keeper/i); await p.waitForTimeout(4000);
ok(!!(await q()).keeper, 'greeting the Keeper is the third');
console.log('  panel:', (await p.evaluate(() => document.getElementById('tasks').innerText)).replace(/\n+/g, ' | '));
await p.screenshot({ path: '/home/claude/ember-isle/shots/q2.png' });
await p.click('#journal-btn'); await p.waitForTimeout(600);
await p.screenshot({ path: '/home/claude/ember-isle/shots/q3.png' });
console.log(errs.length ? [...new Set(errs)].slice(0, 5).join('\n') : 'no page errors', fails ? `${fails} FAILED` : '');
await browser.close();
