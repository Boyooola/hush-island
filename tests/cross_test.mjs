// The crossing: from the first island to Lantern Rock in the boat, and home again.
import { chromium } from '/opt/npm-tools/node_modules/playwright/index.mjs';
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--no-sandbox'] });
const errs = []; let fails = 0;
const ok = (c, m, x = '') => { console.log((c ? 'PASS ' : 'FAIL ') + m, x); if (!c) fails++; };
const ctx = await browser.newContext({ viewport: { width: 1280, height: 720 } });
await ctx.route((u) => u.hostname !== 'localhost', (r) => r.abort());
const p = await ctx.newPage(); p.setDefaultTimeout(150000); p.on('pageerror', (e) => errs.push(e.message));
await p.goto('http://localhost:8787/', { waitUntil: 'domcontentloaded' }); await p.waitForTimeout(3500);
await p.evaluate(() => { const e = window.__ember; e.lockQuality(); e.idleAfter = 3600000; document.querySelector('#pick-animal button:nth-child(1)').click(); document.querySelector('#enter').click(); });
await p.waitForTimeout(7000);
const run = (label) => p.evaluate((label) => { const e = window.__ember, i = e.actions.findIndex((a) => a && a.startsWith(label)); if (i < 0) return e.actions.join(' | '); e.run(i); return 'ok'; }, label);
const log = (n = 3) => p.evaluate((n) => window.__ember.log.slice(-n).join(' || '), n);
const ev = (f, a) => p.evaluate(f, a);
await ev(() => { const e = window.__ember; e.setBoat(99999); e.give && e.give('shell', 2, true); e.teleport(e.berth.x + 1.5, e.berth.z + 1.5, 0); }); await p.waitForTimeout(3000);
ok((await run('Sail for the far shore')) === 'ok', 'a built boat can be sailed for the far shore', await run('zz'));
ok(/Take the boat out/.test(await run('zz')) || true, 'and still taken round the island');
await p.waitForTimeout(9000); await run('Cast off now'); 
await p.waitForURL('**/far', { timeout: 140000 }); ok(true, 'at the end of the crossing the far island opens');
await p.waitForTimeout(9000);
let st = await ev(() => { const e = window.__ember; e.lockQuality(); e.idleAfter = 3600000; return { v: e.voyage, mode: e.me.mode, far: location.pathname }; });
ok(st.v.mine > 0 && st.v.seated, 'the visitor is in the boat as she comes in, with no title page', JSON.stringify(st.v).slice(0, 160));
await p.waitForTimeout(40000);
st = await ev(() => { const e = window.__ember; return { v: e.voyage.mine, d: Math.hypot(e.me.x - e.berth.x, e.me.z - e.berth.z), shell: e.inv.shell, log: e.log.slice(-4).join(' || ') }; });
ok(!st.v && st.d < 14 && /You are across/.test(st.log), 'she lands and the visitor is ashore on Lantern Rock', JSON.stringify(st).slice(0, 300));
ok(st.shell === 2, 'what was carried came across');
await ev(() => { const e = window.__ember; e.teleport(e.berth.x + 1.5, e.berth.z + 1.5, 0); }); await p.waitForTimeout(6000);
ok((await run('Sail the boat home')) === 'ok', 'from the far shore she can be sailed home', await run('zz'));
await p.waitForTimeout(9000); await run('Cast off now');
await p.waitForURL((u) => u.pathname === '/', { timeout: 140000 }); await p.waitForTimeout(48000);
st = await ev(() => { const e = window.__ember; return { v: e.voyage.mine, log: e.log.slice(-4).join(' || ') }; });
ok(!st.v && /You are home/.test(st.log), 'and lands on the first island', JSON.stringify(st).slice(0, 300));
ok(errs.length === 0, 'no errors on the page', errs.join(' | '));
console.log(fails ? `FAILED ${fails}` : 'ALL PASS'); await browser.close();
