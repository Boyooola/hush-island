import { chromium } from '/opt/npm-tools/node_modules/playwright/index.mjs';
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--no-sandbox'] });
const errs = []; let fails = 0;
const ok = (c, m, x = '') => { console.log((c ? 'PASS ' : 'FAIL ') + m, x); if (!c) fails++; };
const ctx = await browser.newContext({ viewport: { width: 1280, height: 720 } });
await ctx.route((u) => u.hostname !== 'localhost', (r) => r.abort());
const p = await ctx.newPage(); p.on('pageerror', (e) => errs.push(e.message));
await p.goto('http://localhost:8787/far', { waitUntil: 'domcontentloaded' }); await p.waitForTimeout(3500);
await p.evaluate(() => { window.__ember.lockQuality(); window.__ember.idleAfter = 3600000; window.__ember.setHour(11); });
await p.click('#pick-animal button:nth-child(1)'); await p.click('#enter'); await p.waitForTimeout(5000);
const S = '/home/claude/ember-isle/shots/';
const go = async (x, z, yaw, cam, wait = 2500) => { await p.evaluate(([x, z, yaw, cam]) => { const e = window.__ember; e.teleport(x, z, yaw); e.cam(...cam); }, [x, z, yaw, cam]); await p.waitForTimeout(wait); };
const run = (label) => p.evaluate((label) => { const e = window.__ember, i = e.actions.indexOf(label); if (i < 0) return e.actions.join(' | '); e.run(i); return 'ok'; }, label);
const st = await p.evaluate(() => window.__ember.world.stones.map((s) => ({ x: s.x, z: s.z })));
ok(st.length === 7, 'seven stones stand on the meadow');
ok(await p.evaluate(() => document.querySelector('.brand b').textContent) === 'The far shore', 'the island has no name to begin with');
await go(-270, -20, 0, [0.7, 0.55, 17], 7000); await p.screenshot({ path: S + 'x1.png' });
console.log(' ', await p.evaluate(() => window.__ember.log.slice(-1)[0]));
let n = 0;
for (const i of [2, 5, 0, 3, 6]) { const s = st[i]; await go(s.x + (-270 - s.x) * 0.2, s.z + (-20 - s.z) * 0.2, 0, [0.7, 0.55, 17], 1800); if ((await run('Touch the standing stone')) === 'ok') n++; await p.waitForTimeout(700); }
ok(n === 5, 'each stone can be touched', n);
await p.waitForTimeout(4500); await p.screenshot({ path: S + 'x2.png' });
ok(await p.evaluate(() => localStorage.getItem('ember.tune') === 'true'), 'playing the wind\'s five notes back is the tune');
await p.waitForTimeout(9000);
ok(await p.evaluate(() => !!window.__emberCards().stones), 'and a stamp');
await p.waitForTimeout(9000);
await go(-265.6, -1.2, 2, [-0.6, 0.35, 9], 9000); await p.screenshot({ path: S + 'x3.png' });
ok(await p.evaluate(() => document.querySelector('.brand b').textContent) === 'Lantern Rock', 'at the top the island gets its name back');
ok(await p.evaluate(() => !!window.__emberCards().summit), 'and the top is a stamp');
await p.click('#journal-btn'); await p.waitForTimeout(800); await p.screenshot({ path: S + 'x4.png' });
console.log(errs.length ? [...new Set(errs)].slice(0, 5).join('\n') : 'no page errors', fails ? `${fails} FAILED` : '');
await browser.close();
