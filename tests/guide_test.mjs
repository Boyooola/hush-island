// The guide: a first visit is led through four steps, then pointed at the keeper's list.
import { chromium } from '/opt/npm-tools/node_modules/playwright/index.mjs';
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--no-sandbox'] });
const errs = [];
const ok = (name, cond, extra = '') => console.log((cond ? 'PASS ' : 'FAIL ') + name + (extra ? '  ' + extra : ''));
const ctx = await browser.newContext({ viewport: { width: 1280, height: 720 } });
const page = await ctx.newPage();
page.on('pageerror', (e) => errs.push(e.message));
await page.goto('http://localhost:8787/index.html');
await page.waitForTimeout(2500);
await page.evaluate(() => { window.__ember.lockQuality(); });
await page.click('#pick-animal button:nth-child(3)');
await page.click('#enter'); await page.waitForTimeout(5000);
const ev = (fn, a) => page.evaluate(fn, a);
const goalLine = () => ev(() => document.getElementById('goal').hidden ? null : document.getElementById('goal').innerText.replace(/\n/g, ' '));
await ev(() => { const e = window.__ember; e.setHour(12); e.setRain(0); });
let g = await ev(() => window.__ember.goal);
ok('a newcomer is told to walk to the fire', g && g.text.startsWith('Walk up to the fire') && Math.hypot(g.x, g.z) < 1, await goalLine());
await page.screenshot({ path: '/home/claude/ember-isle/shots/g1-start.png' });
await ev(() => { const e = window.__ember; e.teleport(2.0, -1.6, 0); e.cam(2.3, 0.35, 6); });
await page.waitForTimeout(2000);
ok('reaching the fire moves on to resting', (await ev(() => window.__ember.goal.text)).startsWith('Rest by the fire'), await goalLine());
await ev(() => window.__ember.run(0)); await page.waitForTimeout(2000);
g = await ev(() => window.__ember.goal);
ok('resting moves on to the stick, pointing at the woodpile', /^Get up/.test(g.text) && Math.abs(g.x - 3.1) < 0.2, await goalLine());
await ev(() => { const e = window.__ember; e.standUp(); e.teleport(3.1, 6.3, Math.PI); }); await page.waitForTimeout(1200);
await page.screenshot({ path: '/home/claude/ember-isle/shots/g2-woodpile.png' });
ok('at the woodpile it says to pick one up', /^Pick up a stick/.test(await ev(() => window.__ember.goal.text)), await goalLine());
await ev(() => window.__ember.run(0)); await page.waitForTimeout(1500);
g = await ev(() => window.__ember.goal);
ok('with a stick in the mouth the guide points back at the fire', Math.hypot(g.x, g.z) < 1 && /^Carry the stick/.test(g.text), await goalLine());
await ev(() => { const e = window.__ember; e.teleport(2.4, 3.0, Math.PI); }); await page.waitForTimeout(900);
ok('by the fire it says to drop it', /^Drop the stick on the fire/.test(await ev(() => window.__ember.goal.text)), await goalLine());
await ev(() => window.__ember.run(0)); await page.waitForTimeout(5000);
ok('feeding the fire moves on to the keeper', (await ev(() => window.__ember.goal.text)).startsWith('Greet the keeper'), await goalLine());
const kp = await ev(() => { const k = window.__ember.keeper; return [k.x, k.z]; });
await ev((kp) => { const d = Math.hypot(kp[0], kp[1]); window.__ember.teleport(kp[0] * (1 + 1.9 / d), kp[1] * (1 + 1.9 / d)); }, kp);
await page.waitForTimeout(900);
await ev(() => { const e = window.__ember; e.run(e.actions.indexOf('Greet the keeper')); }); await page.waitForTimeout(2500);
g = await ev(() => window.__ember.goal);
const list = await ev(() => window.__ember.listToday());
ok('after the four steps the guide takes up the keeper\'s list', (await ev(() => window.__ember.starterAt)) === 4 && g && !g.step, (await goalLine()) + ' | list ' + list.join(','));
ok('the hand-over is explained', await ev(() => [...document.querySelectorAll('#log .line')].some((l) => l.textContent.includes('how the island works'))));
await ev(() => { const e = window.__ember; e.teleport(0.5, 20, Math.PI); e.cam(0.3, 0.25, 9); }); await page.waitForTimeout(2500);
await page.screenshot({ path: '/home/claude/ember-isle/shots/g3-list.png' });
await page.reload(); await page.waitForTimeout(2500);
await page.click('#enter'); await page.waitForTimeout(4000);
ok('a returning visitor skips the four steps', (await ev(() => window.__ember.starterAt)) === 4 && !(await ev(() => window.__ember.goal.step)), await goalLine());
await ctx.close();
const ph = await (await browser.newContext({ viewport: { width: 390, height: 780 }, hasTouch: true, isMobile: true })).newPage();
ph.on('pageerror', (e) => errs.push(e.message));
await ph.goto('http://localhost:8787/index.html'); await ph.waitForTimeout(2500);
await ph.screenshot({ path: '/home/claude/ember-isle/shots/g4-phone-title.png' });
await ph.tap('#enter'); await ph.waitForTimeout(5000);
await ph.screenshot({ path: '/home/claude/ember-isle/shots/g5-phone.png' });
console.log('phone goal:', await ph.evaluate(() => document.getElementById('goal').innerText.replace(/\n/g, ' ')));
console.log(errs.length ? errs.slice(0, 3).join('\n') : 'no page errors');
await browser.close(); process.exit(0);
