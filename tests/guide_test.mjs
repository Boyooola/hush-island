// The guide: a first visit is shown the way to the fire and nothing more; the rest is counted as it is found.
import { chromium } from '/opt/npm-tools/node_modules/playwright/index.mjs';
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--no-sandbox', '--disable-background-timer-throttling', '--disable-renderer-backgrounding', '--disable-backgrounding-occluded-windows'] });
const errs = [];
const ok = (name, cond, extra = '') => console.log((cond ? 'PASS ' : 'FAIL ') + name + (extra ? '  ' + extra : ''));
const stats = async () => { const d = (await (await fetch('http://localhost:8787/room/stats.json')).json()).days; const t = d[Object.keys(d).sort().pop()] || {}; return t; };
const before = await stats();
const open = async (late = 0) => {
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 720 } });
  await ctx.route((u) => u.hostname !== 'localhost', (r) => r.abort());
  if (late) await ctx.addInitScript((late) => { const real = Date.now.bind(Date); Date.now = () => real() + late; }, late);
  const page = await ctx.newPage(); page.on('pageerror', (e) => errs.push(e.message));
  await page.goto('http://localhost:8787/index.html', { waitUntil: 'domcontentloaded' }); await page.waitForTimeout(2500);
  await page.evaluate(() => { window.__ember.lockQuality(); window.__ember.idleAfter = 3600000; });
  await page.click('#pick-animal button:nth-child(3)');
  await page.click('#enter'); await page.waitForTimeout(5000);
  await page.evaluate(() => { const e = window.__ember; e.setHour(12); e.setRain(0); });
  return page;
};
const page = await open();
const ev = (fn, a) => page.evaluate(fn, a);
const goalLine = () => ev(() => document.getElementById('goal').hidden ? null : document.getElementById('goal').innerText.replace(/\n/g, ' '));
let g = await ev(() => window.__ember.goal);
ok('a newcomer is told to walk to the fire', g && g.text.startsWith('Walk up to the fire') && Math.hypot(g.x, g.z) < 1 && !/of/.test(await goalLine()), await goalLine());
ok('the keeper\'s list is out of the way until then', await ev(() => getComputedStyle(document.getElementById('tasks')).display === 'none'));
await ev(() => { const e = window.__ember; e.teleport(2.0, -1.6, 0); e.cam(2.3, 0.35, 6); });
await page.waitForTimeout(2500);
g = await ev(() => window.__ember.goal);
const list = await ev(() => window.__ember.listToday());
ok('reaching the fire ends the guide and hands over to the keeper\'s list', (await ev(() => window.__ember.starterAt)) === 1 && g && !/Rest by the fire/.test(g.text) && await ev(() => getComputedStyle(document.getElementById('tasks')).display !== 'none'), (await goalLine()) + ' | list ' + list.join(','));
ok('what the keys do is said once', await ev(() => window.__ember.log.join(' ').includes('E and R do whatever is in reach')));
ok('resting is offered where you stand', /by the fire/.test(await ev(() => JSON.stringify(window.__ember.actions))), await ev(() => JSON.stringify(window.__ember.actions)));
await page.screenshot({ path: '/home/claude/ember-isle/shots/g1-fire.png' });
await ev(() => { const e = window.__ember; e.run(e.actions.findIndex((x) => /by the fire/.test(x || ''))); }); await page.waitForTimeout(2500);
const kp = await ev(() => { const k = window.__ember.keeper; return [k.x, k.z]; });
await ev((kp) => { const e = window.__ember; e.standUp(); const d = Math.hypot(kp[0], kp[1]); e.teleport(kp[0] * (1 + 1.9 / d), kp[1] * (1 + 1.9 / d)); }, kp);
await page.waitForTimeout(1200);
await ev(() => { const e = window.__ember; e.run(e.actions.indexOf('Greet the keeper')); }); await page.waitForTimeout(3000);
const after = await stats(), d = (k) => (after[k] || 0) - (before[k] || 0);
ok('finding things alone is still counted: fire, rest, keeper, not the stick', d('g1') === 1 && d('g2') === 1 && d('g4') === 1 && d('g3') === 0, ['g0', 'g1', 'g2', 'g3', 'g4'].map((k) => k + ':' + d(k)).join(' '));
await page.reload({ waitUntil: 'domcontentloaded' }); await page.waitForTimeout(2500);
await page.click('#enter'); await page.waitForTimeout(4000);
await ev(() => { const e = window.__ember; e.teleport(2.0, -1.6, 0); }); await page.waitForTimeout(1200);
await ev(() => { const e = window.__ember; e.run(e.actions.findIndex((x) => /by the fire/.test(x || ''))); }); await page.waitForTimeout(2000);
const again = await stats();
ok('a returning visitor is not guided or counted twice', (await ev(() => window.__ember.starterAt)) === 1 && (again.g2 || 0) === (after.g2 || 0) && (again.g1 || 0) === (after.g1 || 0));
// The island's clock: a device ninety seconds fast goes by the island's time, not its own.
const fast = await open(90000);
const sk = await fast.evaluate(() => window.__ember.skew), sk0 = await ev(() => window.__ember.skew);
ok('a fast device is corrected, a true one left alone', Math.abs(sk + 90000) < 1500 && Math.abs(sk0) < 1500, sk + ' ' + sk0);
for (const p of [page, fast]) await p.evaluate(() => { const e = window.__ember; e.setBoat(120); e.standUp(); e.teleport(e.yard.site.x + (e.skew ? 1.2 : 0), e.yard.site.z + 0.6, 0); });
await page.waitForTimeout(1500);
await ev(() => window.__ember.boardBoat()); await page.waitForTimeout(4000);
const [l1, l2] = await Promise.all([page, fast].map((p) => p.evaluate(() => window.__ember.voyage.left)));
ok('both see the same countdown on the boat', l1 > 20 && Math.abs(l1 - l2) < 2.5, l1.toFixed(1) + ' ' + l2.toFixed(1));
const [h1, h2] = await Promise.all([page, fast].map((p) => p.evaluate(() => (window.__ember.timeNow() % 3600000) / 1000)));
ok('and the same hour of the day', Math.abs(h1 - h2) < 2.5, h1.toFixed(1) + ' ' + h2.toFixed(1));
console.log(errs.length ? errs.slice(0, 3).join('\n') : 'no page errors');
await browser.close(); process.exit(0);
